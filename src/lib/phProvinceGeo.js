// Aggregate province features into their region for the regional boundary layer.
// Regions are ordered to draw larger hinterland regions first so overlay joins
// stay clean looking.
export const PH_REGIONS_FEATURES = (() => {
  const map = {};
  for (const f of PH_PROVINCES_FEATURES) {
    if (!map[f.region]) map[f.region] = { name: f.region, region: f.region, rings: [] };
    map[f.region].rings.push(...f.rings);
  }
  return Object.values(map);
})();

